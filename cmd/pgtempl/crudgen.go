package main

import (
	"fmt"
	"sort"
	"strings"
)

// CrudGenerator emits Create/Get/Update/Delete for one table into Package, on a
// *Receiver. Types come from the matched model's db-tagged fields.
type CrudGenerator struct {
	Package    string          // e.g. "orderrepo"
	Receiver   string          // e.g. "Repository"
	ModelPkg   string          // e.g. "ordermodel"; if set, entity type is qualified
	ModelPath  string          // import path for ModelPkg, e.g. "shopnexus-server/internal/module/order/model"
	LocalTypes map[string]bool // type names declared in the model package (structs, enums, …)
}

// qual qualifies a bare model-package-local type with ModelPkg (e.g. "Status" ->
// "ordermodel.Status"). Handles []T and *T prefixes. Leaves builtins and already-
// qualified types (with a ".") untouched.
func (g *CrudGenerator) qual(t string) string {
	if g.ModelPkg == "" {
		return t
	}
	prefix := ""
	for {
		if strings.HasPrefix(t, "[]") {
			prefix += "[]"
			t = t[2:]
		} else if strings.HasPrefix(t, "*") {
			prefix += "*"
			t = t[1:]
		} else {
			break
		}
	}
	if g.LocalTypes[t] && !strings.Contains(t, ".") {
		return prefix + g.ModelPkg + "." + t
	}
	return prefix + t
}

// crudItem pairs a table with its matched entity model.
type crudItem struct {
	table *Table
	model *ModelStruct
}

// GenerateCRUD returns the full Go source for one table, or "" to skip it
// (vector tables, or tables without a single-column primary key).
func (g *CrudGenerator) GenerateCRUD(table *Table, model *ModelStruct) (string, error) {
	return g.GenerateFile([]crudItem{{table, model}})
}

// GenerateFile emits one Go source file containing the CRUD+List for every item,
// sharing a single package decl and a merged import block. Items that skip
// (vector / no single-column PK) contribute nothing. Returns "" if all skip.
func (g *CrudGenerator) GenerateFile(items []crudItem) (string, error) {
	imp := newImportSet(g.Package)
	var bodies strings.Builder
	n := 0
	for _, it := range items {
		body, skip, err := g.crudBody(it.table, it.model, &imp)
		if err != nil {
			return "", err
		}
		if skip {
			continue
		}
		if n > 0 {
			bodies.WriteString("\n")
		}
		bodies.WriteString(body)
		n++

		// Append list body for this table (only when ModelPkg is set and table qualifies).
		lb := g.listBody(it.table, it.model, &imp)
		if lb != "" {
			bodies.WriteString("\n")
			bodies.WriteString(lb)
		}
	}
	if n == 0 {
		return "", nil
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by pgtempl; DO NOT EDIT.\npackage %s\n\n", g.Package)
	b.WriteString(imp.block())
	b.WriteString("\n\n")
	b.WriteString(bodies.String())
	return b.String(), nil
}

// crudBody writes the types + methods for one table (no package/imports),
// accumulating any imports its types need into imp. skip=true for vector tables
// or tables without a single-column primary key.
func (g *CrudGenerator) crudBody(table *Table, model *ModelStruct, imp *importSet) (body string, skip bool, err error) {
	if table.HasVectorColumn() || len(table.PrimaryKeys) != 1 {
		return "", true, nil
	}

	field := func(col *Column) (ModelField, error) {
		mf, ok := model.ByDB[col.Name]
		if !ok {
			return ModelField{}, fmt.Errorf("table %s column %q has no db-tagged field in model %s",
				table.QualifiedName(), col.Name, model.Name)
		}
		return mf, nil
	}

	entity := model.Name
	if g.ModelPkg != "" {
		entity = g.ModelPkg + "." + model.Name
		imp.ext[g.ModelPkg] = g.ModelPath
	}
	suffix := toPascalCase(table.Name)
	pk := table.PrimaryKeys[0]
	pkField, err := field(pk)
	if err != nil {
		return "", false, err
	}

	usesUpdate := len(table.UpdatableColumns()) > 0

	var b strings.Builder

	// ---- Create ----
	insertCols := table.InsertableColumns()
	fmt.Fprintf(&b, "type Create%sParams struct {\n", suffix)
	for _, col := range insertCols {
		mf, err := field(col)
		if err != nil {
			return "", false, err
		}
		imp.useType(mf, model)
		fmt.Fprintf(&b, "\t%s %s\n", mf.GoName, g.qual(mf.GoType))
	}
	b.WriteString("}\n\n")

	imp.useType(pkField, model)
	fmt.Fprintf(&b, "func (r *%s) Create%s(ctx context.Context, arg Create%sParams) (%s, error) {\n",
		g.Receiver, suffix, suffix, pkField.GoType)
	insertNames, insertPlaceholders, insertArgs := insertParts(table, insertCols, model)
	fmt.Fprintf(&b, "\tvar pk %s\n", pkField.GoType)
	fmt.Fprintf(&b, "\terr := r.db.QueryRow(ctx, `INSERT INTO %s (%s)\n\t\tVALUES (%s)\n\t\tRETURNING %s`,\n",
		table.FullName(), insertNames, insertPlaceholders, pk.Quoted())
	fmt.Fprintf(&b, "\t\tpgx.NamedArgs{%s}).Scan(&pk)\n", insertArgs)
	b.WriteString("\treturn pk, err\n}\n\n")

	// ---- Get ----
	imp.useType(pkField, model)
	fmt.Fprintf(&b, "func (r *%s) Get%s(ctx context.Context, id %s) (%s, error) {\n",
		g.Receiver, suffix, pkField.GoType, entity)
	selectCols, scanTargets, err := rowParts(table, model, imp)
	if err != nil {
		return "", false, err
	}
	fmt.Fprintf(&b, "\tvar i %s\n", entity)
	fmt.Fprintf(&b, "\terr := r.db.QueryRow(ctx, `SELECT %s FROM %s WHERE %s = @id`,\n",
		selectCols, table.FullName(), pk.Quoted())
	fmt.Fprintf(&b, "\t\tpgx.NamedArgs{\"id\": id}).Scan(%s)\n", scanTargets)
	b.WriteString("\treturn i, err\n}\n\n")

	// ---- Update (only if there are updatable columns) ----
	if usesUpdate {
		imp.patch = true
		imp.strings = true
		fmt.Fprintf(&b, "type Update%sParams struct {\n", suffix)
		for _, col := range table.UpdatableColumns() {
			mf, err := field(col)
			if err != nil {
				return "", false, err
			}
			imp.useType(mf, model)
			fmt.Fprintf(&b, "\t%s patch.Optional[%s]\n", mf.GoName, g.qual(mf.GoType))
		}
		b.WriteString("}\n\n")

		fmt.Fprintf(&b, "func (r *%s) Update%s(ctx context.Context, id %s, arg Update%sParams) (%s, error) {\n",
			g.Receiver, suffix, pkField.GoType, suffix, pkField.GoType)
		fmt.Fprintf(&b, "\tset := make([]string, 0, %d)\n", len(table.UpdatableColumns()))
		b.WriteString("\targs := pgx.NamedArgs{\"id\": id}\n")
		for _, col := range table.UpdatableColumns() {
			mf := model.ByDB[col.Name]
			fmt.Fprintf(&b, "\tif arg.%s.Set {\n\t\tset = append(set, `%s = @%s`)\n\t\targs[%q] = arg.%s.Value\n\t}\n",
				mf.GoName, col.Quoted(), col.Name, col.Name, mf.GoName)
		}
		b.WriteString("\tif len(set) == 0 {\n\t\treturn id, nil\n\t}\n")
		fmt.Fprintf(&b, "\tsql := `UPDATE %s SET ` + strings.Join(set, \", \") + ` WHERE %s = @id RETURNING %s`\n",
			table.FullName(), pk.Quoted(), pk.Quoted())
		fmt.Fprintf(&b, "\tvar pk %s\n", pkField.GoType)
		b.WriteString("\terr := r.db.QueryRow(ctx, sql, args).Scan(&pk)\n\treturn pk, err\n}\n\n")
	}

	// ---- Delete ----
	fmt.Fprintf(&b, "func (r *%s) Delete%s(ctx context.Context, id %s) error {\n",
		g.Receiver, suffix, pkField.GoType)
	fmt.Fprintf(&b, "\t_, err := r.db.Exec(ctx, `DELETE FROM %s WHERE %s = @id`, pgx.NamedArgs{\"id\": id})\n",
		table.FullName(), pk.Quoted())
	b.WriteString("\treturn err\n}\n")

	return b.String(), false, nil
}

// listBody emits the List method and supporting types for one table onto the
// *Receiver, reusing repogen helpers. Returns "" when skipped (vector table,
// key-only table, or no ModelPkg configured).
func (g *CrudGenerator) listBody(table *Table, model *ModelStruct, imp *importSet) string {
	if g.ModelPkg == "" {
		return ""
	}
	if len(table.UpdatableColumns()) == 0 || table.HasVectorColumn() {
		return ""
	}

	entity := g.ModelPkg + "." + model.Name
	suffix := toPascalCase(table.Name)
	listFunc := "List" + suffix
	filterType := listFunc + "Params"
	queryFunc := suffix + "Query"
	condsFunc := suffix + "Conds"

	// Mark paginate + repolist imports needed.
	imp.paginate = true
	imp.repolist = true
	// Ensure model package is imported.
	imp.ext[g.ModelPkg] = g.ModelPath

	var ri repoImports
	var structLines, condLines []string
	for _, col := range table.FilterableColumns() {
		// Skip enum columns: their IN-filter element type is either a model-
		// package-local type (e.g. Status) or an enumGoName that is undefined in
		// the repo package. Detect via: (a) the DB column is a schema-qualified
		// user type (isEnum), or (b) the matched model field's base Go type is in
		// LocalTypes.
		if isEnum(col) {
			continue
		}
		if mf, ok := model.ByDB[col.Name]; ok {
			base := mf.GoType
			for strings.HasPrefix(base, "[]") || strings.HasPrefix(base, "*") {
				if strings.HasPrefix(base, "[]") {
					base = base[2:]
				} else {
					base = base[1:]
				}
			}
			if g.LocalTypes[base] {
				continue
			}
		}
		ff, ok := buildFilterField(col, &ri)
		if !ok {
			continue
		}
		structLines = append(structLines, ff.structLines...)
		condLines = append(condLines, ff.condLines...)
	}
	// Propagate repoImports into importSet.
	if ri.uuid {
		imp.ext["uuid"] = "github.com/google/uuid"
	}
	if ri.null {
		imp.ext["null"] = "github.com/guregu/null/v6"
	}
	if ri.time {
		imp.stdTime = true
	}

	// fieldRef returns the field reference for a column using model's GoName when
	// available, falling back to goFieldName.
	fieldRef := func(colName string) string {
		if mf, ok := model.ByDB[colName]; ok {
			return mf.GoName
		}
		return goFieldName(colName)
	}

	var b strings.Builder

	// Params struct.
	fmt.Fprintf(&b, "type %s struct {\n\tpaginate.Params\n\n%s\n}\n\n", filterType, strings.Join(structLines, "\n"))

	// Query: reusable static base.
	fmt.Fprintf(&b, "func %s() repolist.Query[%s] {\n", queryFunc, entity)
	fmt.Fprintf(&b, "\treturn repolist.Query[%s]{\n", entity)
	fmt.Fprintf(&b, "\t\tTable: `%s`,\n", table.FullName())
	fmt.Fprintf(&b, "\t\tPK: %q,\n", pkLogical(table))
	fmt.Fprintf(&b, "\t\tSort: []string{%s},\n", buildSortList(table))
	fmt.Fprintf(&b, "\t\tFields: func(m *%s) map[string]any {\n", entity)
	var fieldLines []string
	for _, col := range table.Columns {
		fieldLines = append(fieldLines, fmt.Sprintf("\t\t\t\t%q: &m.%s,", col.Name, fieldRef(col.Name)))
	}
	fmt.Fprintf(&b, "\t\t\treturn map[string]any{\n%s\n\t\t\t}\n\t\t},\n", strings.Join(fieldLines, "\n"))
	b.WriteString("\t}\n}\n\n")

	// Conds.
	fmt.Fprintf(&b, "func %s(f %s) []repolist.Cond {\n", condsFunc, filterType)
	fmt.Fprintf(&b, "\treturn []repolist.Cond{\n%s\n\t}\n}\n\n", strings.Join(condLines, "\n"))

	// List method on *Receiver.
	fmt.Fprintf(&b, "func (r *%s) %s(ctx context.Context, f %s) (paginate.PaginateResult[%s], error) {\n",
		g.Receiver, listFunc, filterType, entity)
	fmt.Fprintf(&b, "\treturn repolist.List(ctx, r.db, f.Params, %s().Filter(%s(f)...))\n}\n", queryFunc, condsFunc)

	return b.String()
}

// insertParts builds the column list, @placeholders, and NamedArgs entries.
func insertParts(table *Table, cols []*Column, model *ModelStruct) (names, placeholders, args string) {
	var ns, ps, as []string
	for _, col := range cols {
		mf := model.ByDB[col.Name]
		ns = append(ns, col.Quoted())
		ps = append(ps, "@"+col.Name)
		as = append(as, fmt.Sprintf("%q: arg.%s", col.Name, mf.GoName))
	}
	return strings.Join(ns, ", "), strings.Join(ps, ", "), strings.Join(as, ", ")
}

// rowParts builds the SELECT column list and matching Scan targets in DDL order.
func rowParts(table *Table, model *ModelStruct, imp *importSet) (selectCols, scanTargets string, err error) {
	var cs, ts []string
	for _, col := range table.Columns {
		mf, ok := model.ByDB[col.Name]
		if !ok {
			return "", "", fmt.Errorf("table %s column %q has no db-tagged field in model %s",
				table.QualifiedName(), col.Name, model.Name)
		}
		imp.useType(mf, model)
		cs = append(cs, col.Quoted())
		ts = append(ts, "&i."+mf.GoName)
	}
	return strings.Join(cs, ", "), strings.Join(ts, ", "), nil
}

// importSet accumulates the import lines a generated file needs.
type importSet struct {
	selfPkg  string
	strings  bool
	stdTime  bool
	patch    bool
	paginate bool
	repolist bool
	ext      map[string]string // localName -> path (from model types)
}

func newImportSet(pkg string) importSet {
	return importSet{selfPkg: pkg, ext: map[string]string{}}
}

// useType records the imports a model field's type references.
func (s *importSet) useType(mf ModelField, model *ModelStruct) {
	for local := range usedQualifiers2(mf.GoType) {
		if path, ok := model.Imports[local]; ok {
			s.ext[local] = path
		}
	}
}

// usedQualifiers2 finds "pkg." qualifiers inside a rendered type string.
// Note: usedQualifiers (no suffix) operates on the AST in modelparser.go;
// this variant operates on rendered type strings in the generator.
func usedQualifiers2(goType string) map[string]bool {
	found := map[string]bool{}
	for _, tok := range strings.FieldsFunc(goType, func(r rune) bool {
		return !(r == '.' || r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9')
	}) {
		if i := strings.IndexByte(tok, '.'); i > 0 {
			found[tok[:i]] = true
		}
	}
	return found
}

// isStdlibPath reports whether an import path belongs to the Go standard
// library. Stdlib root segments never contain a dot (no domain) and never
// contain a hyphen (no module names). E.g. "time", "encoding/json" → true;
// "shopnexus-server/…", "github.com/…" → false.
func isStdlibPath(path string) bool {
	seg := path
	if i := strings.IndexByte(path, '/'); i >= 0 {
		seg = path[:i]
	}
	return !strings.Contains(seg, ".") && !strings.Contains(seg, "-")
}

func (s *importSet) block() string {
	// Stdlib group: always context; optionally strings, time.
	stdSet := map[string]bool{`"context"`: true}
	if s.strings {
		stdSet[`"strings"`] = true
	}
	if s.stdTime {
		stdSet[`"time"`] = true
	}

	// Fixed third-party / internal entries (keyed by quoted path for dedup).
	thirdSet := map[string]bool{`"github.com/jackc/pgx/v5"`: true}
	if s.patch {
		thirdSet[`"shopnexus-server/internal/shared/patch"`] = true
	}
	if s.paginate {
		thirdSet[`"shopnexus-server/internal/shared/paginate"`] = true
	}
	if s.repolist {
		thirdSet[`"shopnexus-server/internal/shared/repolist"`] = true
	}

	// ext entries: classify and deduplicate. Stdlib paths (first segment has no
	// dot) go into stdSet; everything else into third-party unless already present.
	var extThird []string
	for local, path := range s.ext {
		quoted := fmt.Sprintf("%q", path)
		var line string
		// Emit an explicit alias whenever the qualifier differs from the last
		// path segment — covers versioned paths (null/v6 → null) and renamed
		// packages (order/model → ordermodel).
		if seg := path[strings.LastIndexByte(path, '/')+1:]; seg != local {
			line = fmt.Sprintf("%s %q", local, path)
		} else {
			line = quoted
		}
		if isStdlibPath(path) {
			// Promote to stdlib group; skip adding to ext list.
			stdSet[quoted] = true
			continue
		}
		if thirdSet[quoted] {
			// Already covered by a fixed entry.
			continue
		}
		extThird = append(extThird, line)
	}

	var std []string
	for entry := range stdSet {
		std = append(std, entry)
	}
	var third []string
	for entry := range thirdSet {
		third = append(third, entry)
	}
	third = append(third, extThird...)

	sort.Strings(std)
	sort.Strings(third)

	var b strings.Builder
	b.WriteString("import (\n\t")
	b.WriteString(strings.Join(std, "\n\t"))
	if len(third) > 0 {
		b.WriteString("\n\n\t")
		b.WriteString(strings.Join(third, "\n\t"))
	}
	b.WriteString("\n)")
	return b.String()
}

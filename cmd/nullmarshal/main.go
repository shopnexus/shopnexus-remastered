package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// outName is the generated sibling file written next to each models.go.
// It is fully regenerated every run, so it never collides with sqlc output.
const outName = "models_json.go"

func main() {
	pattern := "internal/module/*/db/sqlc/models.go"
	matches, err := filepath.Glob(pattern)
	if err != nil {
		panic(err)
	}
	if len(matches) == 0 {
		fmt.Println("no models.go files found")
		return
	}
	for _, path := range matches {
		if err := processFile(path); err != nil {
			fmt.Fprintf(os.Stderr, "error processing %s: %v\n", path, err)
		} else {
			fmt.Println("processed", path)
		}
	}
}

type nullTypeInfo struct {
	typeName  string
	innerName string
}

func processFile(path string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.AllErrors)
	if err != nil {
		return fmt.Errorf("parse: %w", err)
	}

	var nullTypes []nullTypeInfo

	for _, decl := range f.Decls {
		d, ok := decl.(*ast.GenDecl)
		if !ok || d.Tok != token.TYPE {
			continue
		}
		for _, spec := range d.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || !strings.HasPrefix(ts.Name.Name, "Null") {
				continue
			}
			st, ok := ts.Type.(*ast.StructType)
			if !ok || len(st.Fields.List) != 2 {
				continue
			}
			lastField := st.Fields.List[1]
			if isIdent(lastField.Type, "bool") && lastField.Names != nil && lastField.Names[0].Name == "Valid" {
				nullTypes = append(nullTypes, nullTypeInfo{
					typeName:  ts.Name.Name,
					innerName: st.Fields.List[0].Names[0].Name,
				})
			}
		}
	}

	outPath := filepath.Join(filepath.Dir(path), outName)

	if len(nullTypes) == 0 {
		// No Null types — drop any stale generated file.
		if err := os.Remove(outPath); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	}

	fmt.Println("  writing", len(nullTypes), "marshalers to", outPath)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by cmd/nullmarshal. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", f.Name.Name)
	fmt.Fprintf(&buf, "import \"encoding/json\"\n\n")
	for _, nt := range nullTypes {
		fmt.Fprintf(&buf, `func (n %[1]s) MarshalJSON() ([]byte, error) {
	if !n.Valid {
		return []byte("null"), nil
	}
	return json.Marshal(n.%[2]s)
}

func (n *%[1]s) UnmarshalJSON(b []byte) error {
	if string(b) == "null" {
		n.Valid = false
		return nil
	}
	n.Valid = true
	return json.Unmarshal(b, &n.%[2]s)
}

`, nt.typeName, nt.innerName)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}

	return os.WriteFile(outPath, formatted, 0644)
}

func isIdent(expr ast.Expr, name string) bool {
	ident, ok := expr.(*ast.Ident)
	return ok && ident.Name == name
}

// Command genenum generates a Valid() method and a nullable wrapper
// (NullXxx{Value, Valid} with null-aware JSON) for string enum types.
//
// Usage, as a go:generate directive above the enum declaration:
//
//	//go:generate go run shopnexus-server/cmd/genenum -type=Status,Role
//
// It reads the invoking file from $GOFILE (set by `go generate`) and writes
// <file>_gen.go next to it. For each requested `type X string` it emits:
//
//	func (e X) Valid() bool          // true iff e is one of the declared consts
//	type NullX struct { Value X; Valid bool }
//	func (n NullX) MarshalJSON()     // "null" when !Valid, else the value
//	func (n *NullX) UnmarshalJSON()  // "null" -> Valid=false
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

func main() {
	typeList := flag.String("type", "", "comma-separated enum type names to generate")
	input := flag.String("file", os.Getenv("GOFILE"), "source file (defaults to $GOFILE)")
	output := flag.String("output", "", "output file (defaults to <file>_gen.go)")
	flag.Parse()

	if *typeList == "" || *input == "" {
		fmt.Fprintln(os.Stderr, "genenum: -type and a source file (via $GOFILE or -file) are required")
		os.Exit(2)
	}

	want := strings.Split(*typeList, ",")
	for i := range want {
		want[i] = strings.TrimSpace(want[i])
	}

	out := *output
	if out == "" {
		out = strings.TrimSuffix(*input, ".go") + "_gen.go"
	}

	if err := run(*input, out, want); err != nil {
		fmt.Fprintf(os.Stderr, "genenum: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("genenum:", out)
}

func run(input, output string, want []string) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, input, nil, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("parse %s: %w", input, err)
	}

	consts := collectConsts(f) // type name -> ordered const names

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by genenum; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", f.Name.Name)
	buf.WriteString("import \"encoding/json\"\n")

	for _, name := range want {
		members := consts[name]
		if len(members) == 0 {
			return fmt.Errorf("type %q: no string consts found in %s", name, input)
		}
		writeType(&buf, name, members)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n%s", err, buf.String())
	}
	return os.WriteFile(output, src, 0o644)
}

// collectConsts maps each named type to the const identifiers declared with it,
// in source order. Honors Go's const-block type inheritance.
func collectConsts(f *ast.File) map[string][]string {
	out := map[string][]string{}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		var lastType string
		for _, spec := range gd.Specs {
			vs, ok := spec.(*ast.ValueSpec)
			if !ok {
				continue
			}
			if id, ok := vs.Type.(*ast.Ident); ok {
				lastType = id.Name
			}
			if lastType == "" {
				continue
			}
			for _, n := range vs.Names {
				if n.Name == "_" {
					continue
				}
				out[lastType] = append(out[lastType], n.Name)
			}
		}
	}
	return out
}

func writeType(buf *bytes.Buffer, name string, members []string) {
	fmt.Fprintf(buf, `
func (e %[1]s) Valid() bool {
	switch e {
	case %[2]s:
		return true
	}
	return false
}

type Null%[1]s struct {
	Value %[1]s `+"`json:\"value\"`"+`
	Valid bool  `+"`json:\"valid\"`"+`
}

func (n Null%[1]s) MarshalJSON() ([]byte, error) {
	if !n.Valid {
		return []byte("null"), nil
	}
	return json.Marshal(n.Value)
}

func (n *Null%[1]s) UnmarshalJSON(b []byte) error {
	if string(b) == "null" {
		n.Valid = false
		return nil
	}
	n.Valid = true
	return json.Unmarshal(b, &n.Value)
}
`, name, strings.Join(members, ", "))
}
